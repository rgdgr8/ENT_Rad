package technology.cariad.entertainment.metadataservice.data.database.entity

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import androidx.room.TypeConverters
import technology.cariad.entertainment.metadataservice.data.database.converter.OriginTypeConverter
import technology.cariad.entertainment.metadataservice.domain.entity.ProviderIdentifierEntity.Companion.OriginType

/**
 * Representation of the provider identifier table and database entries stored within.
 * A [ProviderIdentifierEntry] encapsulates the information from which backend service the
 * associated information was provided.
 */
@TypeConverters(OriginTypeConverter::class)
@Entity(
    tableName = "provider_identifier",
    indices = [
        Index(
            name = "index_provider_identifier_origin_external_id",
            value = ["origin", "external_id"],
            unique = true
        )
    ]
)
data class ProviderIdentifierEntry(

    /**
     * Autogenerated primary key.
     */
    @PrimaryKey(autoGenerate = true)
    @ColumnInfo(name = "provider_id")
    val providerId: Long = 0,

    /**
     *
     */
    @ColumnInfo(name = "origin")
    val origin: OriginType,

    /**
     *
     */
    @ColumnInfo(name = "external_id")
    val externalId: String
)

