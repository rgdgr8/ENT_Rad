package de.esolutions.connectedradioclient.handlers.media

import android.content.Context
import android.net.Network
import de.esolutions.connectedradioclient.BuildConfig
import de.esolutions.connectedradioclient.api.Http
import de.esolutions.connectedradioclient.data.AccountManagerConfig
import de.esolutions.connectedradioclient.data.Config
import de.esolutions.connectedradioclient.data.ETags
import de.esolutions.connectedradioclient.data.EndpointConfig
import de.esolutions.connectedradioclient.data.MediaRequestObject
import de.esolutions.connectedradioclient.data.bearer.IBearer
import de.esolutions.connectedradioclient.debug.DebugConfig
import de.esolutions.connectedradioclient.debug.DebugController
import de.esolutions.connectedradioclient.handlers.backend.controller.IController
import de.esolutions.connectedradioclient.handlers.backend.controller.RequestController
import de.esolutions.connectedradioclient.handlers.backend.executor.ExecutorWorker
import de.esolutions.connectedradioclient.handlers.coreservices.TokenHandler
import de.esolutions.connectedradioclient.irc.IRC
import de.esolutions.connectedradioclient.logger.Logger
import de.esolutions.connectedradioclient.logger.LoggerTags
import de.esolutions.connectedradioclient.logger.PrivacyFlags

class ConRadClient(context: Context, loggerChannelRoot: String?) {

    companion object {
        private var initCount: Int = 0
    }

    /**
     * Initialize Logger and IRC, if we got a logger channel root.
     * Logger channel root will be null if the code gets executed by a test.
     * Logger and IRC are only available on emulator, otherwise it uses stdout.
     */
    init {
        val clientInitializationNumber = ++initCount

        loggerChannelRoot?.let {
            Logger.init(it)
        }
        Logger.i(
            PrivacyFlags.SAFE,
            null,
            "Client initialisation $clientInitializationNumber with version: ${BuildConfig.VERSION_NAME}"
        )

        IRC.printVersionInformation()
    }

    private val requestController: RequestController = RequestController(context)
    private val debugController: DebugController = DebugController()
    private var controller: IController = requestController

    /**
     * Push the request to the current controller.
     * Create a [MediaRequestObject] from the given [bearer], [eTags] and [callback].
     *
     * @param bearer Bearer to query at the backend.
     * @param eTags The eTags of the data (previously generated by the backend).
     * @param callback Interface to which all data are transferred.
     */
    fun getRadioStationData(
        bearer: IBearer,
        eTags: ETags,
        callback: IRadioStationDataCallback
    ) {
        controller.getRadioStationData(MediaRequestObject(bearer, eTags, callback))
    }

    /**
     * Stops the job queue and sets the given Network to the HttpClient,
     * if the Network is not null, the job queue is restarted.
     */
    fun setNetwork(network: Network?) {
        Logger.i(
            PrivacyFlags.SAFE,
            null,
            "Receive new network. NetworkID: $network",
            LoggerTags.NETWORK
        )

        ExecutorWorker.stop()

        network?.let {
            Http.setNetwork(it)
            ExecutorWorker.start()
        }
    }

    /**
     * Saves the given [accountManagerConfig] and [endpointConfig] information.
     */
    fun setConfig(
        accountManagerConfig: AccountManagerConfig,
        endpointConfig: EndpointConfig
    ) {
        Logger.i(
            PrivacyFlags.SAFE,
            null,
            "Receive account manager config: $accountManagerConfig",
            LoggerTags.CONFIG
        )

        Logger.i(
            PrivacyFlags.SAFE,
            null,
            "Receive endpoint config: $endpointConfig",
            LoggerTags.CONFIG
        )

        TokenHandler.accountManagerConfig = accountManagerConfig
        Config.endpointConfig = endpointConfig
    }

    /**
     * Uses the given [token] for all backend requests.
     * If the [token] is null, it will request one from core services.
     */
    fun setToken(token: String?) {
        Logger.i(
            PrivacyFlags.TOKEN,
            null,
            "Receive token from media: ${Logger.trimToken(token)}",
            LoggerTags.TOKEN,
            LoggerTags.CONFIG
        )

        TokenHandler.debugToken = token
    }

    /**
     * Switch the current controller.
     * If [debugConfig] is null, use the [RequestController]
     * If [debugConfig] is not null, use the [DebugController]
     * and send the [debugConfig] to the controller.
     */
    fun setDebugConfig(debugConfig: DebugConfig?) {
        if (debugConfig == null) {
            this.controller = this.requestController
        } else {
            this.debugController.setDebugConfig(debugConfig)
            this.controller = this.debugController
        }
    }
}