#!/usr/bin/env kotlin
/**
 * RPC2AIDL Code Generator — Cariad Edition
 *
 * Parses IMetadataService.kt (RxJava interface) and generates:
 *   1. AIDL callback interfaces (*.aidl)
 *   2. IMetadataServiceAidl.aidl (Binder interface)
 *   3. IMetadataServiceManagement.aidl (client registration)
 *   4. IMetadataServiceClientAdapter.kt (client-side RxJava→AIDL bridge)
 *   5. IMetadataServiceAidlProviderAdapter.kt (server-side AIDL→RxJava bridge)
 *
 * Usage: kotlinc -script rpc2aidl.main.kts <path-to-IMetadataService.kt> <output-dir>
 */

import java.io.File

// ── Data model ──────────────────────────────────────────────────────────────────

data class RpcMethod(
    val name: String,
    val params: List<Param>,        // parameters of the RxJava method
    val rxKind: RxKind,             // Single or Observable
    val resultType: String,         // inner type: "Boolean", "Station", …
    val callbackAidlType: String,   // e.g. "BooleanSingleCallback", "StationCallback"
)

data class Param(val name: String, val type: String)

enum class RxKind { SINGLE, OBSERVABLE }

// ── Parsing ─────────────────────────────────────────────────────────────────────

fun parseInterface(file: File): List<RpcMethod> {
    val src = file.readText()
    // Match: fun <name>(<params>): Single<Type>  or  fun <name>(<params>): Observable<Type>
    val pattern = Regex(
        """fun\s+(\w+)\s*\(([^)]*)\)\s*:\s*(Single|Observable)\s*<\s*([^>]+)\s*>"""
    )
    return pattern.findAll(src).map { m ->
        val name = m.groupValues[1]
        val rawParams = m.groupValues[2].trim()
        val rxKindStr = m.groupValues[3]
        val resultType = m.groupValues[4].trim()

        val params = if (rawParams.isEmpty()) emptyList() else {
            rawParams.split(",").map { p ->
                val parts = p.trim().split(":").map { it.trim() }
                Param(parts[0], parts[1])
            }
        }

        val rxKind = if (rxKindStr == "Single") RxKind.SINGLE else RxKind.OBSERVABLE
        val callbackType = callbackTypeName(rxKind, resultType)

        RpcMethod(name, params, rxKind, resultType, callbackType)
    }.toList()
}

fun callbackTypeName(kind: RxKind, resultType: String): String {
    return when (kind) {
        RxKind.SINGLE -> "${resultType}SingleCallback"
        RxKind.OBSERVABLE -> "${resultType}Callback"
    }
}

// ── AIDL type mapping ───────────────────────────────────────────────────────────

/** Map Kotlin types to AIDL parameter types */
fun aidlType(kt: String): String = when (kt) {
    "Boolean" -> "boolean"
    "Int" -> "int"
    "Long" -> "long"
    "Float" -> "float"
    "Double" -> "double"
    "String" -> "String"
    else -> kt  // Parcelable types pass through
}

/** Check if a type needs an AIDL parcelable declaration */
fun isParcelable(type: String): Boolean = type !in setOf(
    "Boolean", "Int", "Long", "Float", "Double", "String",
    "boolean", "int", "long", "float", "double"
)

/** Check if AIDL type is a primitive (no 'in' keyword needed) */
fun isPrimitive(aidlType: String): Boolean = aidlType in setOf(
    "boolean", "int", "long", "float", "double"
)

// ── Generator: AIDL callbacks ───────────────────────────────────────────────────

/** Create a meaningful AIDL parameter name from a type */
fun aidlParamName(type: String): String = when (type) {
    "Boolean", "boolean" -> "bool"
    "String" -> "value"
    else -> type.replaceFirstChar { it.lowercase() }
}

fun generateCallbackAidl(method: RpcMethod): Pair<String, String> {
    val cb = method.callbackAidlType
    val fileName = "$cb.aidl"
    val resultAidl = aidlType(method.resultType)
    val paramName = aidlParamName(method.resultType)
    val inPrefix = if (!isPrimitive(resultAidl) && resultAidl != "String") "in " else ""

    val body = buildString {
        appendLine("// Generated by rpc2aidl — DO NOT EDIT")
        appendLine("package technology.cariad.entertainment.metadataserviceclient.api;")
        appendLine()
        if (isParcelable(method.resultType)) {
            appendLine("import technology.cariad.entertainment.metadataserviceclient.api.${method.resultType};")
            appendLine()
        }
        appendLine("interface $cb {")
        when (method.rxKind) {
            RxKind.SINGLE -> {
                appendLine("    void onSuccess($inPrefix$resultAidl $paramName);")
                appendLine("    void onError(String message);")
            }
            RxKind.OBSERVABLE -> {
                appendLine("    void onNext($inPrefix$resultAidl $paramName);")
                appendLine("    void onComplete();")
                appendLine("    void onError(String message);")
            }
        }
        appendLine("}")
    }
    return fileName to body
}

// ── Generator: Parcelable declarations ──────────────────────────────────────────

fun generateParcelableAidl(typeName: String): String = buildString {
    appendLine("// Generated by rpc2aidl — DO NOT EDIT")
    appendLine("package technology.cariad.entertainment.metadataserviceclient.api;")
    appendLine("parcelable $typeName;")
}

fun collectParcelableTypes(methods: List<RpcMethod>): Set<String> {
    val types = mutableSetOf<String>()
    for (m in methods) {
        if (isParcelable(m.resultType)) types.add(m.resultType)
        for (p in m.params) {
            if (isParcelable(p.type)) types.add(p.type)
        }
    }
    return types
}

// ── Generator: IMetadataServiceAidl.aidl ────────────────────────────────────────

fun generateServiceAidl(methods: List<RpcMethod>): String = buildString {
    appendLine("// Generated by rpc2aidl — DO NOT EDIT")
    appendLine("package technology.cariad.entertainment.metadataserviceclient.api;")
    appendLine()
    appendLine("import technology.cariad.entertainment.metadataserviceclient.api.IMetadataServiceManagement;")

    // Collect imports
    val imports = mutableSetOf<String>()
    for (m in methods) {
        imports.add(m.callbackAidlType)
        for (p in m.params) {
            if (isParcelable(p.type)) imports.add(p.type)
        }
    }
    for (imp in imports.sorted()) {
        appendLine("import technology.cariad.entertainment.metadataserviceclient.api.$imp;")
    }
    appendLine()
    appendLine("interface IMetadataServiceAidl {")
    appendLine("    IMetadataServiceManagement management();")
    appendLine()
    for (m in methods) {
        // Subscribe method
        val subscribeParams = buildList {
            add("int clientId")
            add("int requestId")
            for (p in m.params) {
                val at = aidlType(p.type)
                val prefix = if (!isPrimitive(at) && at != "String" && isParcelable(p.type)) "in " else ""
                add("$prefix$at ${p.name}")
            }
            add("${m.callbackAidlType} callback")
        }
        appendLine("    void ${m.name}Subscribe(${subscribeParams.joinToString(", ")});")
        appendLine("    void ${m.name}Dispose(int clientId, int requestId);")
        appendLine()
    }
    appendLine("}")
}

