// ── Generator: IMetadataServiceClientAdapter.kt ─────────────────────────────────

fun generateClientAdapter(methods: List<RpcMethod>): String = buildString {
    appendLine("// Generated by rpc2aidl — DO NOT EDIT")
    appendLine("package technology.cariad.entertainment.metadataserviceclient.api")
    appendLine()
    appendLine("import android.content.Context")
    appendLine("import io.reactivex.rxjava3.core.Observable")
    appendLine("import io.reactivex.rxjava3.core.Single")
    appendLine("import io.reactivex.rxjava3.core.Scheduler")
    appendLine("import java.util.concurrent.atomic.AtomicInteger")
    appendLine()
    appendLine("class IMetadataServiceClientAdapter(")
    appendLine("    private val aidl: IMetadataServiceAidl,")
    appendLine("    private val context: Context,")
    appendLine("    private val scheduler: Scheduler")
    appendLine(") : IMetadataService {")
    appendLine()
    appendLine("    private val clientBinder = android.os.Binder()")
    appendLine("    private val clientId: Int = aidl.management().registerClient(toString(), clientBinder)")
    appendLine("    private var requestIdCounter = AtomicInteger(0)")
    appendLine()

    for (m in methods) {
        val paramDecl = m.params.joinToString(", ") { "${it.name}: ${it.type}" }
        val paramNames = m.params.map { it.name }

        when (m.rxKind) {
            RxKind.SINGLE -> {
                appendLine("    override fun ${m.name}($paramDecl): Single<${m.resultType}> {")
                appendLine("        return Single.create<${m.resultType}> { emitter ->")
                appendLine("            val requestId = requestIdCounter.getAndIncrement()")
                appendLine("            val callback = object : ${m.callbackAidlType}.Stub() {")
                appendLine("                override fun onSuccess(value: ${m.resultType}) {")
                appendLine("                    if (!emitter.isDisposed) emitter.onSuccess(value)")
                appendLine("                }")
                appendLine("                override fun onError(message: String) {")
                appendLine("                    if (!emitter.isDisposed) emitter.onError(RuntimeException(message))")
                appendLine("                }")
                appendLine("            }")
                val callArgs = buildList {
                    add("clientId"); add("requestId")
                    addAll(paramNames)
                    add("callback")
                }.joinToString(", ")
                appendLine("            aidl.${m.name}Subscribe($callArgs)")
                appendLine("            emitter.setCancellable { aidl.${m.name}Dispose(clientId, requestId) }")
                appendLine("        }.subscribeOn(scheduler)")
                appendLine("    }")
            }
            RxKind.OBSERVABLE -> {
                appendLine("    override fun ${m.name}($paramDecl): Observable<${m.resultType}> {")
                appendLine("        return Observable.create<${m.resultType}> { emitter ->")
                appendLine("            val requestId = requestIdCounter.getAndIncrement()")
                appendLine("            val callback = object : ${m.callbackAidlType}.Stub() {")
                appendLine("                override fun onNext(value: ${m.resultType}) {")
                appendLine("                    if (!emitter.isDisposed) emitter.onNext(value)")
                appendLine("                }")
                appendLine("                override fun onComplete() {")
                appendLine("                    if (!emitter.isDisposed) emitter.onComplete()")
                appendLine("                }")
                appendLine("                override fun onError(message: String) {")
                appendLine("                    if (!emitter.isDisposed) emitter.onError(RuntimeException(message))")
                appendLine("                }")
                appendLine("            }")
                val callArgs = buildList {
                    add("clientId"); add("requestId")
                    addAll(paramNames)
                    add("callback")
                }.joinToString(", ")
                appendLine("            aidl.${m.name}Subscribe($callArgs)")
                appendLine("            emitter.setCancellable { aidl.${m.name}Dispose(clientId, requestId) }")
                appendLine("        }.subscribeOn(scheduler)")
                appendLine("    }")
            }
        }
        appendLine()
    }
    appendLine("    companion object {")
    appendLine("        fun fromBinder(")
    appendLine("            binder: android.os.IBinder,")
    appendLine("            context: Context,")
    appendLine("            scheduler: Scheduler = io.reactivex.rxjava3.schedulers.Schedulers.io()")
    appendLine("        ): IMetadataService = IMetadataServiceClientAdapter(")
    appendLine("            IMetadataServiceAidl.Stub.asInterface(binder), context, scheduler")
    appendLine("        )")
    appendLine("    }")
    appendLine("}")
}

// ── Generator: IMetadataServiceAidlProviderAdapter.kt ───────────────────────────

fun generateProviderAdapter(methods: List<RpcMethod>): String = buildString {
    appendLine("// Generated by rpc2aidl — DO NOT EDIT")
    appendLine("package technology.cariad.entertainment.metadataserviceclient.api")
    appendLine()
    appendLine("import android.content.Context")
    appendLine("import android.os.Binder")
    appendLine("import android.os.IBinder")
    appendLine("import android.os.IInterface")
    appendLine("import io.reactivex.rxjava3.core.Scheduler")
    appendLine("import io.reactivex.rxjava3.disposables.Disposable")
    appendLine("import java.util.concurrent.ConcurrentHashMap")
    appendLine("import java.util.concurrent.atomic.AtomicInteger")
    appendLine()
    appendLine("class IMetadataServiceAidlProviderAdapter(")
    appendLine("    private val rpc: IMetadataService,")
    appendLine("    private val context: Context,")
    appendLine("    private val scheduler: Scheduler,")
    appendLine("    private val onTransactCall: () -> Unit = {}")
    appendLine(") : IMetadataServiceAidl.Stub() {")
    appendLine()
    appendLine("    private var clientCounter = AtomicInteger(0)")
    appendLine("    private val subscriptions = ConcurrentHashMap<Pair<Int, Int>, Disposable>()")
    appendLine("    private val ids = ConcurrentHashMap<Int, Pair<Int, Int>>()")
    appendLine()
    appendLine("    override fun management(): IMetadataServiceManagement {")
    appendLine("        return object : IMetadataServiceManagement.Stub() {")
    appendLine("            override fun registerClient(clientName: String, deathRecipient: IBinder): Int {")
    appendLine("                val id = clientCounter.getAndIncrement()")
    appendLine("                deathRecipient.linkToDeath({ disposeAllForClient(id) }, 0)")
    appendLine("                return id")
    appendLine("            }")
    appendLine("            override fun unregisterClient(clientId: Int, clientName: String) {")
    appendLine("                disposeAllForClient(clientId)")
    appendLine("            }")
    appendLine("            override fun registerClientWithIds(clientName: String, deathRecipient: IBinder, clientId: Int, requestId: Int): Int {")
    appendLine("                val id = clientCounter.getAndIncrement()")
    appendLine("                ids[id] = Pair(clientId, requestId)")
    appendLine("                deathRecipient.linkToDeath({ disposeAllForClient(id) }, 0)")
    appendLine("                return id")
    appendLine("            }")
    appendLine("        }")
    appendLine("    }")
    appendLine()
    appendLine("    private fun disposeAllForClient(clientId: Int) {")
    appendLine("        subscriptions.keys.filter { it.first == clientId }.forEach { key ->")
    appendLine("            subscriptions.remove(key)?.dispose()")
    appendLine("        }")
    appendLine("    }")
    appendLine()

    for (m in methods) {
        val subscribeParams = buildList {
            add("clientId: Int")
            add("requestId: Int")
            for (p in m.params) add("${p.name}: ${p.type}")
            add("callback: ${m.callbackAidlType}")
        }.joinToString(", ")

        appendLine("    override fun ${m.name}Subscribe($subscribeParams) {")
        appendLine("        scheduler.scheduleDirect {")

        val rpcCallArgs = m.params.joinToString(", ") { it.name }
        val rpcCall = if (rpcCallArgs.isEmpty()) "rpc.${m.name}()" else "rpc.${m.name}($rpcCallArgs)"

        when (m.rxKind) {
            RxKind.SINGLE -> {
                appendLine("            val disposable = $rpcCall")
                appendLine("                .subscribe(")
                appendLine("                    { value -> callback.onSuccess(value) },")
                appendLine("                    { error -> callback.onError(error.message ?: \"unknown\") }")
                appendLine("                )")
                appendLine("            subscriptions[Pair(clientId, requestId)] = disposable")
            }
            RxKind.OBSERVABLE -> {
                appendLine("            val disposable = $rpcCall")
                appendLine("                .subscribe(")
                appendLine("                    { value -> callback.onNext(value) },")
                appendLine("                    { error -> callback.onError(error.message ?: \"unknown\") },")
                appendLine("                    { callback.onComplete() }")
                appendLine("                )")
                appendLine("            subscriptions[Pair(clientId, requestId)] = disposable")
            }
        }
        appendLine("        }")
        appendLine("    }")
        appendLine()
        appendLine("    override fun ${m.name}Dispose(clientId: Int, requestId: Int) {")
        appendLine("        subscriptions.remove(Pair(clientId, requestId))?.dispose()")
        appendLine("    }")
        appendLine()
    }

    appendLine("    override fun onTransact(code: Int, data: android.os.Parcel, reply: android.os.Parcel?, flags: Int): Boolean {")
    appendLine("        onTransactCall()")
    appendLine("        return super.onTransact(code, data, reply, flags)")
    appendLine("    }")
    appendLine("}")
}

// ── Main ────────────────────────────────────────────────────────────────────────

fun main(args: Array<String>) {
    if (args.size < 2) {
        System.err.println("Usage: rpc2aidl.main.kts <IMetadataService.kt> <output-dir>")
        System.exit(1)
    }

    val inputFile = File(args[0])
    val outputDir = File(args[1])

    if (!inputFile.exists()) {
        System.err.println("Input file not found: ${inputFile.absolutePath}")
        System.exit(1)
    }

    println("RPC2AIDL Generator — Cariad Edition")
    println("Input:  ${inputFile.absolutePath}")
    println("Output: ${outputDir.absolutePath}")
    println()

    val methods = parseInterface(inputFile)
    println("Parsed ${methods.size} RPC methods:")
    for (m in methods) {
        println("  ${m.rxKind.name.lowercase().replaceFirstChar { it.uppercase() }}<${m.resultType}> ${m.name}(${m.params.joinToString { "${it.name}: ${it.type}" }})")
    }
    println()

    // Create output directories
    val aidlDir = File(outputDir, "aidl/technology/cariad/entertainment/metadataserviceclient/api")
    val kotlinDir = File(outputDir, "java/technology/cariad/entertainment/metadataserviceclient/api")
    aidlDir.mkdirs()
    kotlinDir.mkdirs()

    // 1. Generate callback AIDL files (deduplicated by callback type name)
    val seenCallbacks = mutableSetOf<String>()
    for (m in methods) {
        if (m.callbackAidlType in seenCallbacks) continue
        seenCallbacks.add(m.callbackAidlType)
        val (fileName, content) = generateCallbackAidl(m)
        File(aidlDir, fileName).writeText(content)
        println("Generated: aidl/…/$fileName")
    }

    // 2. Generate IMetadataServiceAidl.aidl
    File(aidlDir, "IMetadataServiceAidl.aidl").writeText(generateServiceAidl(methods))
    println("Generated: aidl/…/IMetadataServiceAidl.aidl")

    // 3. Generate IMetadataServiceManagement.aidl
    File(aidlDir, "IMetadataServiceManagement.aidl").writeText(generateManagementAidl())
    println("Generated: aidl/…/IMetadataServiceManagement.aidl")

    // 4. Generate IMetadataServiceClientAdapter.kt
    File(kotlinDir, "IMetadataServiceClientAdapter.kt").writeText(generateClientAdapter(methods))
    println("Generated: java/…/IMetadataServiceClientAdapter.kt")

    // 5. Generate IMetadataServiceAidlProviderAdapter.kt
    File(kotlinDir, "IMetadataServiceAidlProviderAdapter.kt").writeText(generateProviderAdapter(methods))
    println("Generated: java/…/IMetadataServiceAidlProviderAdapter.kt")

    // 6. Generate parcelable AIDL declarations
    val parcelables = collectParcelableTypes(methods)
    for (type in parcelables.sorted()) {
        File(aidlDir, "$type.aidl").writeText(generateParcelableAidl(type))
        println("Generated: aidl/…/$type.aidl (parcelable)")
    }

    println()
    println("Done! Generated ${seenCallbacks.size} callbacks + ${parcelables.size} parcelables + 2 AIDL interfaces + 2 Kotlin adapters")
}

main(args)

